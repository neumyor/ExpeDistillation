"""Experiment configuration (stage 0) and its YAML (de)serialisation.

One YAML file under ``configs/experiments/`` describes one experiment. The
frozen copy of this config (``to_dict``) goes into the run manifest; changing
any field after the run started is a new experiment (B4 enforces that).

SCHEMA v9: the method is a ``sequence`` of phases -- local names looked
up under ``phases``, an execute phase (role ``baseline``, ``practice`` or
``test``) or a learn phase each. A phase family's
params are validated by the family's own contract (a dataclass in the
methods layer) at resolution time, not here: core is layer 0 and cannot
know a method's parameters. Core owns only the shape. Any other schema
version is refused; configs are generated by
``scripts/run/build_paper_configs.py``.

The role table is a plain dict on purpose: ``models[role] -> model name``.
Two entries are the anchors -- ``executor_strong`` and ``executor_weak`` --
and every other role defaults to the anchor ``ROLE_DEFAULTS`` names (all of
them the strong model). ``ROLE_DEFAULTS`` is a dict, not a tuple, so the
defaults are data and no longer a namesake of ``core.models``' trajectory
roles.

``token_budgets`` (schema v2) remains the single source of every call's token
caps: a required ``default_max_output_tokens`` whenever the mapping is
present, an optional global ``max_input_tokens`` (null = measure only), and
optional per-role entries under ``roles``. ``max_output_tokens_for``
resolves a role's effective cap and fails closed when no budgets are
configured. ``model_options`` must not carry ``max_tokens`` (or any
request-shape key): a second budget source silently won or lost against
the real one depending on merge order.

Config files fail loud: unknown top-level keys and schema versions other
than this code's are ConfigErrors instead of being silently dropped. The
trap this closes: a new config run by old code dropped ``token_budgets``
without a trace and fell back to the dead 5120 default.

Deviation from the layer rule "core depends on stdlib only": ``load_config``
needs YAML, and the design places it here. The ``yaml``
import is function-local so that importing the data model never pulls the
dependency in.
"""

import dataclasses
import json
import re
from dataclasses import dataclass, field, fields
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple, Union

#: The four lists of an explicit split, in report order. ``train`` and
#: ``test`` are required; ``val`` (the tasks a practice phase may run
#: instead of train) and ``reserved`` (held back from every phase) may be
#: absent, which means empty. The four lists are pairwise disjoint.
SPLIT_LIST_KEYS = ("train", "val", "test", "reserved")
SPLIT_REQUIRED_KEYS = frozenset({"train", "test"})

#: Keys of the named-rule selections.
RULE_KEYS = ("segment_select", "trajectory_select")

#: Rule name per key when the config names none: the segment selection
#: (D6) and the trajectory selection's default (all trajectories). The
#: defaults ARE the method canon.
DEFAULT_RULES = {
    "segment_select": "strong_success_weak_failed",
    "trajectory_select": "all",
}

#: Job role -> the executor anchor it defaults to, "strong" or "weak".
#: Every role but the weak executor answers with the strong model;
#: ``judge`` serves only the judge-skills analysis tool.
ROLE_DEFAULTS: Dict[str, str] = {
    "executor_strong": "strong",
    "executor_weak": "weak",
    "segmenter": "strong",
    "author": "strong",
    "rewriter": "strong",
    "judge": "strong",
}

#: Chat-call keys ``model_options`` must never carry (schema v2):
#: ``max_tokens`` is owned by ``token_budgets`` -- a second source silently
#: won or lost against the real one depending on merge order -- and the rest
#: are not provider knobs: ``model``/``messages``/``stream`` ARE the request,
#: and ``temperature`` belongs to the client, not the experiment identity.
#: model_options forwards per-model sampling knobs (reasoning_effort) and
#: the generic client's cache knobs (cache_mode / cache_prefix_tokens).
MODEL_OPTIONS_RESERVED_KEYS = ("max_tokens", "temperature", "model",
                               "messages", "stream")

#: Keys accepted inside ``token_budgets``.
_TOKEN_BUDGET_KEYS = ("default_max_output_tokens", "max_input_tokens", "roles")

#: Keys accepted inside one ``token_budgets.roles`` entry.
_ROLE_BUDGET_KEYS = ("max_output_tokens", "max_input_tokens")

CONFIG_SCHEMA_VERSION = 9


class ConfigError(ValueError):
    """Invalid experiment config: bad shape, unknown key or bad value.

    Defined in core (not imported from infra.reliability) because core is
    stdlib-only. Subclassing ValueError keeps every existing contract:
    ``cli.run_experiment`` wraps load_config's ValueErrors into infra's
    ConfigError, and callers matching ValueError keep matching.
    """


# ---------------------------------------------------------------------------
# The phase vocabulary and the parsed phase specs
# ---------------------------------------------------------------------------
#
# One method is a SEQUENCE of phases: the config names a list of phase
# LOCAL names and, for each name, a phase definition under ``phases``; the
# same definition may occupy several positions in the sequence (the
# reference method's three learn phases share one definition). Local names
# are restricted to a colon-free charset because the pipeline_log stage
# value and every per-phase path key off the label ``pNN:<local name>``
# (composites.phase_bank and ids.phase_tag both refuse anything else).
#
# Phase specs are DATACLASSES, not TypedDicts, for the same reason the
# rest of core's records are: ``__post_init__`` is where the load-time
# checklist lives (a TypedDict validates nothing at runtime), and the
# frozen manifest serialises them through ``dataclasses.fields`` exactly
# like every other ExperimentConfig field. frozen=True stops attribute
# reassignment on a parsed spec; its mapping fields stay mutable dicts.

#: The explicit phase roles.
PHASE_ROLE_BASELINE = "baseline"  # the two-arm bare run on train, first only
PHASE_ROLE_PRACTICE = "practice"  # the weak model with the bank, train or val
PHASE_ROLE_TEST = "test"          # the final test -- never feeds learning
PHASE_ROLE_LEARN = "learn"        # a learn phase

#: The roles an execute phase may declare (a learn phase is always
#: ``learn``).
EXECUTE_PHASE_ROLES = (PHASE_ROLE_BASELINE, PHASE_ROLE_PRACTICE,
                       PHASE_ROLE_TEST)

#: The execute roles a learn phase may read: its immediately preceding
#: execute phase must be one of these (test results never feed learning).
LEARNABLE_PHASE_ROLES = (PHASE_ROLE_BASELINE, PHASE_ROLE_PRACTICE)

#: What an execute phase runs over: one of the frozen split lists.
PHASE_TASK_SETS = ("train", "val", "test")

#: The task sets each role may run: the baseline runs train, practice runs
#: train or val, and the test role and the test set are one fact.
ROLE_TASK_SETS = {
    PHASE_ROLE_BASELINE: ("train",),
    PHASE_ROLE_PRACTICE: ("train", "val"),
    PHASE_ROLE_TEST: ("test",),
}

#: The delivery family's ``none`` name: no skills, the baseline's delivery.
#: Delivery and execution names live here because core may not import the
#: methods registry; the registry's entries resolve these same literals.
NONE_DELIVERY_NAME = "none"

#: The delivery family's ``folder`` name: the skill-folder delivery, legal
#: on practice and test phases and paired one-to-one with the
#: ``real_folder`` execution.
FOLDER_DELIVERY_NAME = "folder"

#: The execution family's ``real`` name: a benchmark run with the skills
#: (if any) injected into the prompt.
REAL_EXECUTION_NAME = "real"

#: The execution family's ``real_folder`` name: ``real``'s folder twin,
#: the skills reach the agent as a folder of files.
FOLDER_EXECUTION_NAME = "real_folder"

#: Every execution name an execute phase may declare.
EXECUTION_NAMES = (REAL_EXECUTION_NAME, FOLDER_EXECUTION_NAME)

#: The control a test phase's ``compare`` may name: a bare arm run fresh
#: inside the phase.
FRESH_BARE = "fresh_bare"

#: The other control source a ``compare`` may name: the control numbers
#: come from an EXTERNAL campaign's frozen score file (the AgentBrew
#: bare-run archive) instead of any execution this run owns -- the
#: bare control arm is never re-run; the comparison reads the
#: byte-identical campaign harness's numbers. It REQUIRES the
#: ``external`` block naming the score file (path + sha256 + the campaign's
#: model key for this run's weak executor), so the control's identity is
#: pinned in the frozen config exactly like every other method input.
EXTERNAL_CAMPAIGN = "external_campaign"

#: The ``compare.external`` block's required key set.
_EXTERNAL_CONTROL_KEYS = frozenset({"path", "sha256", "model_key"})

#: A pinned sha256: 64 lowercase hex digits.
_SHA256_RE = re.compile(r"[0-9a-f]{64}")

#: The execute phase's playbook switch: ``evolved`` shows the executor the
#: playbook the immediately preceding learn phase wrote, ``off`` shows none.
#: Only practice and test phases may turn it on: the baseline is the bare
#: measurement every learn phase starts from.
PLAYBOOK_OFF = "off"
PLAYBOOK_EVOLVED = "evolved"
PLAYBOOK_SWITCHES = (PLAYBOOK_OFF, PLAYBOOK_EVOLVED)

#: How many times the phase driver may re-dispatch one unit the verdict
#: ruled invalid (R9/R1's redispatch loop; after the limit the unit
#: stays a hole with cause ``invalid_redispatch_exhausted``). A method
#: parameter, not an operational knob: accepting holes changes what is
#: measured.
DEFAULT_INVALID_REDISPATCH_LIMIT = 1

#: Phase local names: colon-free and directory-safe. The colon is the
#: label separator, so it is the one character a name can never carry
#: (ids.parse_trajectory_id re-splits on it; phase_bank maps it to ``_``).
PHASE_NAME_RE = re.compile(r"[A-Za-z0-9._-]+")

#: The pipeline_log stage value of the freeze step: freeze is always
#: ``p00`` and every sequence phase's number is its 0-based sequence
#: index plus one (the frozen phase numbering:
#: ``phases/p{index + 1:02d}_<name>``; the first sequence entry, the
#: baseline, is ``p01_<name>``).
FREEZE_LABEL = "p00:freeze"


def phase_label(index: int, name: str) -> str:
    """The pipeline_log stage value of sequence entry ``index`` (0-based):
    ``pNN:<local name>`` with ``NN = index + 1`` (p00 is the freeze step)."""
    return f"p{index + 1:02d}:{name}"


@dataclass(frozen=True)
class ExternalControlSpec:
    """The frozen score-file identity of an ``external_campaign``
    control: where the campaign's per-task scores live and which of its
    models this run's test executor is.

    ``path`` is resolved against the config file's directory at load
    time (the ``tasks``-path rule) and frozen absolute, so a resume from
    another cwd reads the same file. ``sha256`` pins the exact bytes
    (the control's numbers must not drift with a re-exported campaign
    file), and ``model_key`` names the campaign's prefix for the model the
    test phase runs (the archive covers several models; the wrong
    prefix would compare the bank arm against a different model's
    numbers). The score-file format and the task-alignment checks are
    the loader's (composites/external_control.py), not core's.
    """

    path: str
    sha256: str
    model_key: str


#: The legal ``compare.against`` values.
COMPARE_SOURCES = (FRESH_BARE, EXTERNAL_CAMPAIGN)


@dataclass(frozen=True)
class CompareSpec:
    """A test phase's control: ``fresh_bare`` or ``external_campaign``
    (which requires the ``external`` block)."""

    against: str
    external: Optional[ExternalControlSpec] = None


@dataclass(frozen=True)
class ExecutePhaseSpec:
    """One execute phase (delivery -> execution -> acceptance).

    ``delivery`` / ``execution`` keep the RAW method mappings (a
    ``name`` key plus that method's parameters): core owns the shape,
    the methods layer's contracts validate the parameters at resolution
    (stage 0 resolves every family of every phase before anything
    freezes). ``tasks`` picks the frozen train / val / test id list
    (``ROLE_TASK_SETS``); ``compare``
    is optional; ``acceptance`` names the verdict rule (C11) and
    ``None`` is the benchmark's default (composites.verdicts.
    default_verdict_rule). ``playbook`` is the playbook switch
    (``PLAYBOOK_SWITCHES``).
    """

    role: str
    tasks: str = "train"
    delivery: Dict[str, Any] = field(default_factory=dict)
    execution: Dict[str, Any] = field(default_factory=dict)
    compare: Optional[CompareSpec] = None
    acceptance: Optional[str] = None
    playbook: str = PLAYBOOK_OFF
    kind: str = "execute"

    def __post_init__(self) -> None:
        if self.kind != "execute":
            raise ConfigError(
                f"an execute phase's kind must be 'execute', got "
                f"{self.kind!r}")
        if self.role not in EXECUTE_PHASE_ROLES:
            raise ConfigError(
                f"an execute phase's role must be one of "
                f"{list(EXECUTE_PHASE_ROLES)}, got {self.role!r}")
        if self.tasks not in PHASE_TASK_SETS:
            raise ConfigError(
                f"an execute phase's tasks must be one of "
                f"{list(PHASE_TASK_SETS)}, got {self.tasks!r}")
        if self.playbook not in PLAYBOOK_SWITCHES:
            raise ConfigError(
                f"an execute phase's playbook must be one of "
                f"{list(PLAYBOOK_SWITCHES)}, got {self.playbook!r}")
        if self.playbook == PLAYBOOK_EVOLVED \
                and self.role == PHASE_ROLE_BASELINE:
            raise ConfigError(
                "a baseline phase runs without a playbook; only practice "
                f"and test phases may set playbook {PLAYBOOK_EVOLVED!r}")


@dataclass(frozen=True)
class LearnPhaseSpec:
    """One learn phase (diagnose -> locate -> assign evidence -> evolve the
    profile and the playbook -> evolve the skill bank).

    Learn phases are not registry entries; their content families resolve
    through the registry like any other: ``review`` (segmentation budget
    and lesson material) and ``author`` (the subtask typing and card
    writing parameters). Every learn phase runs the same five steps; it
    reads the failures of the execute phase right before it.
    """

    review: Dict[str, Any] = field(default_factory=dict)
    author: Dict[str, Any] = field(default_factory=dict)
    kind: str = "learn"
    role: str = PHASE_ROLE_LEARN

    def __post_init__(self) -> None:
        if self.kind != "learn":
            raise ConfigError(
                f"a learn phase's kind must be 'learn', got {self.kind!r}")
        if self.role != PHASE_ROLE_LEARN:
            raise ConfigError(
                f"a learn phase's role is always {PHASE_ROLE_LEARN!r}, "
                f"got {self.role!r}")


#: A phase definition: what ``config.phases`` maps a local name to.
PhaseSpec = Union[ExecutePhaseSpec, LearnPhaseSpec]


@dataclass(frozen=True)
class PhaseInstance:
    """One POSITION of the sequence, as the phase driver receives it.

    Built by the CLI's phase loop (cli.py): ``index`` is
    the 0-based sequence position, ``label`` is the pipeline_log stage
    value ``pNN:<name>`` and every per-phase path key, ``spec`` is the
    parsed definition, and ``task_ids`` is the frozen id list this phase
    runs over (the train, val or test list for an execute phase, empty
    for a learn phase). This is the frozen hand-off contract between the
    CLI's phase loop and the two phase drivers' ``run`` entry points.
    """

    index: int
    name: str
    label: str
    spec: PhaseSpec
    task_ids: Tuple[str, ...] = ()


@dataclass(frozen=True)
class PhaseResult:
    """What a phase driver returns to the loop: the phase's JSON-safe
    summary (the ledger line's ``summary``). Drivers may carry more in
    the summary dict; ``label`` is echoed so the loop can assert the
    driver answered for the phase it was asked about."""

    label: str
    summary: Dict[str, Any]


#: The field sets the two kinds accept (checked by parse_phases: a key
#: outside the kind's set is a typo or a version mismatch, never a
#: silent drop -- the same discipline as the unknown top-level key).
_EXECUTE_FIELDS = frozenset({"kind", "role", "tasks", "delivery", "execution",
                             "compare", "acceptance", "playbook"})
_LEARN_FIELDS = frozenset({"kind", "role", "review", "author"})

#: The baseline phase's two arms: fixed by design (the strong arm's
#: successes are the card material, the weak arm's failures the first
#: learn phase's evidence).
BASELINE_ARMS = ("executor_strong", "executor_weak")


def _method_mapping(raw: Any, where: str) -> Dict[str, Any]:
    """One nested method mapping: a dict naming its method. The deep
    validation belongs to the family's contract in the methods layer
    (resolution, stage 0); here only the shape and the ``name`` are
    checked. The returned dict is a one-level copy."""
    if not isinstance(raw, dict):
        raise ConfigError(
            f"{where} must be a mapping of the method's parameter names "
            f"to values, got {type(raw).__name__}")
    name = raw.get("name")
    if not isinstance(name, str) or not name:
        raise ConfigError(f"{where} needs a non-empty 'name'")
    return dict(raw)


def _parse_execute_phase(name: str, raw: Dict[str, Any]) -> ExecutePhaseSpec:
    """One execute phase definition: its field set, the role's task set,
    delivery and execution, the folder pairing and the arms (checklist
    items 2, 3, 5 and 7 of ``parse_phases``)."""
    unknown = sorted(set(raw) - _EXECUTE_FIELDS)
    if unknown:
        raise ConfigError(
            f"phases.{name} is kind 'execute' but carries key(s) {unknown}; "
            f"an execute phase accepts {sorted(_EXECUTE_FIELDS)}")
    role = raw.get("role")
    if role not in EXECUTE_PHASE_ROLES:
        raise ConfigError(
            f"phases.{name}.role must be one of {list(EXECUTE_PHASE_ROLES)}"
            f" (the role is declared, never inferred), got {role!r}")
    tasks = raw.get("tasks", "train")
    if tasks not in PHASE_TASK_SETS:
        raise ConfigError(
            f"phases.{name}.tasks must be one of {list(PHASE_TASK_SETS)}, "
            f"got {tasks!r}")
    # The test role and the test set are one fact: a final test on the
    # train set would leak test results into learning, and a learning
    # phase on the test set would measure on the held-out tasks.
    if tasks not in ROLE_TASK_SETS[role]:
        raise ConfigError(
            f"phases.{name} has role {role!r} with tasks {tasks!r}; that "
            f"role runs {' or '.join(repr(t) for t in ROLE_TASK_SETS[role])}"
            " (the test role runs the test set and only the test role does)")
    delivery = _method_mapping(raw.get("delivery"),
                               f"phases.{name}.delivery")
    execution = _method_mapping(raw.get("execution"),
                                f"phases.{name}.execution")
    exec_name = execution["name"]
    if exec_name not in EXECUTION_NAMES:
        raise ConfigError(
            f"phases.{name}.execution name {exec_name!r} is not one of "
            f"{list(EXECUTION_NAMES)}")
    # The folder delivery and the real_folder execution are one play, so
    # they pair one-to-one: a folder delivery under the plain real
    # execution would inject the catalog as a skills block (silently the
    # wrong experiment), and a real_folder execution over another
    # delivery would expect a folder no delivery produced.
    if (delivery["name"] == FOLDER_DELIVERY_NAME) \
            != (exec_name == FOLDER_EXECUTION_NAME):
        raise ConfigError(
            f"phases.{name} declares delivery name {delivery['name']!r} "
            f"with execution name {exec_name!r}: the "
            f"{FOLDER_DELIVERY_NAME!r} delivery pairs with the "
            f"{FOLDER_EXECUTION_NAME!r} execution, and each with nothing "
            "else")
    if role == PHASE_ROLE_BASELINE and \
            delivery["name"] != NONE_DELIVERY_NAME:
        raise ConfigError(
            f"phases.{name} has role {PHASE_ROLE_BASELINE!r} with delivery "
            f"{delivery['name']!r}; the baseline is the bare run: delivery "
            f"{NONE_DELIVERY_NAME!r} with execution {REAL_EXECUTION_NAME!r}")
    if role == PHASE_ROLE_PRACTICE and \
            delivery["name"] != FOLDER_DELIVERY_NAME:
        raise ConfigError(
            f"phases.{name} has role {PHASE_ROLE_PRACTICE!r} with delivery "
            f"{delivery['name']!r}; a practice phase runs the way the final "
            f"test does: delivery {FOLDER_DELIVERY_NAME!r} with execution "
            f"{FOLDER_EXECUTION_NAME!r}")
    if role == PHASE_ROLE_BASELINE:
        # The two-arm phase; the global n_attempts_strong /
        # n_attempts_weak decide the two depths.
        arms = execution.get("arms")
        if not (isinstance(arms, list) and tuple(arms) == BASELINE_ARMS):
            raise ConfigError(
                f"phases.{name}.execution.arms must be exactly "
                f"{list(BASELINE_ARMS)} (a baseline phase runs both arms; "
                "their depths come from the global n_attempts_strong / "
                "n_attempts_weak)")
    elif "arms" in execution:
        raise ConfigError(
            f"phases.{name}.execution carries arms but only a baseline "
            "phase is two-armed; every other execute phase runs one "
            "executor")
    compare_raw = raw.get("compare")
    compare: Optional[CompareSpec] = None
    if compare_raw is not None:
        if role != PHASE_ROLE_TEST:
            raise ConfigError(
                f"phases.{name} has role {role!r} with a compare block; "
                f"only a {PHASE_ROLE_TEST!r} phase has a control")
        if not isinstance(compare_raw, dict):
            raise ConfigError(
                f"phases.{name}.compare must be a mapping with 'against', "
                f"got {compare_raw!r}")
        unknown = sorted(set(compare_raw) - {"against", "external"})
        if unknown:
            raise ConfigError(
                f"phases.{name}.compare has unknown key(s) {unknown}")
        against = compare_raw.get("against")
        if against not in COMPARE_SOURCES:
            raise ConfigError(
                f"phases.{name}.compare.against must be one of "
                f"{list(COMPARE_SOURCES)}, got {against!r}")
        external_raw = compare_raw.get("external")
        if against == EXTERNAL_CAMPAIGN:
            if not isinstance(external_raw, dict):
                raise ConfigError(
                    f"phases.{name}.compare.against is "
                    f"{EXTERNAL_CAMPAIGN!r} but compare.external is not a "
                    "mapping with path / sha256 / model_key, got "
                    f"{external_raw!r}")
            unknown_external = sorted(
                set(external_raw) - _EXTERNAL_CONTROL_KEYS)
            if unknown_external:
                raise ConfigError(
                    f"phases.{name}.compare.external has unknown key(s) "
                    f"{unknown_external}; required: "
                    f"{sorted(_EXTERNAL_CONTROL_KEYS)}")
            missing_external = sorted(
                key for key in _EXTERNAL_CONTROL_KEYS
                if not isinstance(external_raw.get(key), str)
                or not external_raw[key])
            if missing_external:
                raise ConfigError(
                    f"phases.{name}.compare.external is missing or empty "
                    f"for key(s) {missing_external}; the external control's "
                    "identity (file, checksum, campaign model key) is part "
                    "of the frozen method, never a default")
            sha256 = external_raw["sha256"].strip().lower()
            if not _SHA256_RE.fullmatch(sha256):
                raise ConfigError(
                    f"phases.{name}.compare.external.sha256 must be 64 "
                    f"hex digits, got {external_raw['sha256']!r}")
            external = ExternalControlSpec(
                path=external_raw["path"],
                sha256=sha256,
                model_key=external_raw["model_key"])
        else:
            if external_raw is not None:
                raise ConfigError(
                    f"phases.{name}.compare carries the 'external' block "
                    f"but against is {against!r}: the block belongs to "
                    f"against {EXTERNAL_CAMPAIGN!r} alone")
            external = None
        compare = CompareSpec(against=against, external=external)
    acceptance = raw.get("acceptance")
    if acceptance is not None and (not isinstance(acceptance, str)
                                    or not acceptance):
        raise ConfigError(
            f"phases.{name}.acceptance must name a verdict rule or be "
            f"absent (the benchmark's default), got {acceptance!r}")
    return ExecutePhaseSpec(
        role=role, tasks=tasks, delivery=delivery, execution=execution,
        compare=compare, acceptance=acceptance,
        playbook=raw.get("playbook", PLAYBOOK_OFF), kind="execute")


def _parse_learn_phase(name: str, raw: Dict[str, Any]) -> LearnPhaseSpec:
    """One learn phase definition: shape only -- the content families'
    parameters validate at resolution (the methods layer's contracts)."""
    unknown = sorted(set(raw) - _LEARN_FIELDS)
    if unknown:
        raise ConfigError(
            f"phases.{name} is kind 'learn' but carries key(s) {unknown}; "
            f"a learn phase accepts {sorted(_LEARN_FIELDS)}")
    review = _method_mapping(raw.get("review"), f"phases.{name}.review")
    author = _method_mapping(raw.get("author"), f"phases.{name}.author")
    role = raw.get("role", PHASE_ROLE_LEARN)
    if role != PHASE_ROLE_LEARN:
        raise ConfigError(
            f"phases.{name}.role must be {PHASE_ROLE_LEARN!r} for a learn "
            f"phase, got {role!r}")
    return LearnPhaseSpec(
        review=review, author=author, kind="learn", role=PHASE_ROLE_LEARN)


def parse_phases(raw_phases: Any,
                 raw_sequence: Any) -> Dict[str, PhaseSpec]:
    """Validate the ``sequence`` / ``phases`` pair and return the parsed
    specs, keyed by local name (the sequence may repeat a name; the
    definitions are one per name).

    The load-time checklist (design spec 2.3), each check a ConfigError:

    1. the sequence is a non-empty list of local names over the
       colon-free charset, and every name has a definition (a definition
       the sequence never uses is refused too -- it would freeze method
       identity no phase ever runs);
    2. each definition's field set matches its ``kind``;
    3. the declared role is consistent with the field values: the test
       role runs the test list and only it does; the baseline runs train
       with exactly the two arms, the ``none`` delivery, the ``real``
       execution and playbook ``off``; practice runs train or val with
       the ``folder`` delivery; no other phase carries ``arms``;
    4. only the first entry may be the baseline, and a sequence with a
       learn or a practice phase starts with it (a test-only sequence
       has none);
    5. only a test phase carries ``compare``, naming ``fresh_bare`` or
       ``external_campaign`` with its ``external`` block;
    6. every learn phase's immediately preceding execute phase is a
       baseline or a practice phase;
    7. the ``folder`` delivery and the ``real_folder`` execution pair
       one-to-one;
    8. ``playbook`` is ``off`` or ``evolved``, and an ``evolved`` execute
       phase follows a learn phase.

    Item 9 (the schema version and unknown top-level keys) belongs to
    ``ExperimentConfig.from_dict`` / ``load_config``; a practice phase on
    ``val`` needing a non-empty val list is ExperimentConfig's check too
    (the split is not part of the sequence).
    Model roles and ``invalid_redispatch_limit`` are ExperimentConfig's
    own checks, not the sequence's.
    """
    if not isinstance(raw_sequence, list) or not raw_sequence:
        raise ConfigError(
            "sequence must be a non-empty list of phase names, got "
            f"{raw_sequence!r}")
    for position, entry in enumerate(raw_sequence):
        if not isinstance(entry, str) or not PHASE_NAME_RE.fullmatch(entry):
            raise ConfigError(
                f"sequence entry {position} is {entry!r}: a phase name is "
                "1+ characters over letters, digits, '.', '_', '-' "
                "(never a colon -- the label 'pNN:<name>' and the phase "
                "directories parse on it)")
    if not isinstance(raw_phases, dict) or not raw_phases:
        raise ConfigError(
            "phases must be a non-empty mapping of phase name -> "
            f"definition, got {raw_phases!r}")
    for phase_name in raw_phases:
        if not isinstance(phase_name, str) or not PHASE_NAME_RE.fullmatch(
                phase_name):
            raise ConfigError(
                f"phases key {phase_name!r} is not a legal phase name "
                "(1+ characters over letters, digits, '.', '_', '-')")
    unknown = [entry for entry in raw_sequence if entry not in raw_phases]
    if unknown:
        raise ConfigError(
            f"sequence names phase(s) {unknown} with no definition under "
            f"'phases'; defined: {sorted(raw_phases)}")
    unused = sorted(set(raw_phases) - set(raw_sequence))
    if unused:
        raise ConfigError(
            f"phases defines {unused} but the sequence never runs "
            "them; a definition no phase runs would freeze method "
            "identity nothing measures")
    specs: Dict[str, PhaseSpec] = {}
    for phase_name, raw in raw_phases.items():
        if not isinstance(raw, dict):
            raise ConfigError(
                f"phases.{phase_name} must be a mapping, got "
                f"{type(raw).__name__}")
        kind = raw.get("kind")
        if kind == "execute":
            specs[phase_name] = _parse_execute_phase(phase_name, raw)
        elif kind == "learn":
            specs[phase_name] = _parse_learn_phase(phase_name, raw)
        else:
            raise ConfigError(
                f"phases.{phase_name}.kind must be 'execute' or 'learn', "
                f"got {kind!r}")
    _check_baseline_comes_first(raw_sequence, specs)
    _check_learn_reads_learnable(raw_sequence, specs)
    _check_playbook_has_a_source(raw_sequence, specs)
    return specs


def _check_baseline_comes_first(raw_sequence: List[str],
                                specs: Dict[str, PhaseSpec]) -> None:
    """Checklist item 4: the baseline may only be the first entry, and a
    sequence with a learn or a practice phase starts with it -- the strong
    model's trajectories come from it alone. A test-only sequence (a bank
    prepared by import-bank, or a bare run) has no baseline."""
    learns = any(spec.role in (PHASE_ROLE_LEARN, PHASE_ROLE_PRACTICE)
                 for spec in (specs[name] for name in raw_sequence))
    for position, name in enumerate(raw_sequence):
        spec = specs[name]
        is_baseline = isinstance(spec, ExecutePhaseSpec) \
            and spec.role == PHASE_ROLE_BASELINE
        if position == 0 and learns and not is_baseline:
            raise ConfigError(
                f"the sequence starts with {name!r} (kind "
                f"{spec.kind!r}, role {spec.role!r}); a sequence with a "
                f"{PHASE_ROLE_LEARN!r} or {PHASE_ROLE_PRACTICE!r} phase "
                f"must start with the {PHASE_ROLE_BASELINE!r} execute phase")
        if position > 0 and is_baseline:
            raise ConfigError(
                f"sequence entry {position} ({name!r}) is a "
                f"{PHASE_ROLE_BASELINE!r} phase; only the first entry may "
                "be the baseline")


def _check_learn_reads_learnable(raw_sequence: List[str],
                                 specs: Dict[str, PhaseSpec]) -> None:
    """Checklist item 6: a learn phase reads the failures of the execute
    phase right before it, which must be a baseline or a practice phase
    (test results never feed learning)."""
    last_execute: Optional[ExecutePhaseSpec] = None
    last_name = ""
    for name in raw_sequence:
        spec = specs[name]
        if isinstance(spec, ExecutePhaseSpec):
            last_execute, last_name = spec, name
            continue
        if last_execute is None \
                or last_execute.role not in LEARNABLE_PHASE_ROLES:
            role = None if last_execute is None else last_execute.role
            raise ConfigError(
                f"learn phase {name!r} follows execute phase "
                f"{last_name!r} of role {role!r}; a learn phase reads the "
                f"execute phase right before it, which must be one of "
                f"{list(LEARNABLE_PHASE_ROLES)}")


def _check_playbook_has_a_source(raw_sequence: List[str],
                                 specs: Dict[str, PhaseSpec]) -> None:
    """Checklist item 8: an execute phase with ``playbook: evolved`` reads
    the playbook of the learn phase before it, so every position it
    occupies must follow a learn phase."""
    seen_learn = False
    for name in raw_sequence:
        spec = specs[name]
        if isinstance(spec, LearnPhaseSpec):
            seen_learn = True
        elif spec.playbook == PLAYBOOK_EVOLVED and not seen_learn:
            raise ConfigError(
                f"phases.{name} sets playbook {PLAYBOOK_EVOLVED!r} but no "
                "learn phase runs before it, so there is no playbook to "
                "show")


def phase_spec_to_raw(spec: PhaseSpec) -> Dict[str, Any]:
    """The freezable form of one parsed phase spec: the same shape
    ``parse_phases`` accepts, so ``to_dict`` -> ``from_dict`` round-trips
    (the manifest comparison depends on that)."""
    return dataclasses.asdict(spec)


def _normalise_tasks(tasks: Any) -> Union[None, str, List[str]]:
    """Validate the ``tasks`` field; a tuple of ids becomes a list (the
    frozen manifest is JSON, where a tuple would not compare equal)."""
    if tasks is None:
        return None
    if isinstance(tasks, str):
        if not tasks.strip():
            raise ValueError("tasks path must be a non-empty string")
        return tasks
    if isinstance(tasks, (list, tuple)):
        if not tasks or not all(isinstance(t, str) and t for t in tasks):
            raise ValueError(
                "tasks must be a non-empty list of task-id strings, "
                f"got {tasks!r}")
        seen: set = set()
        duplicates = set()
        for task_id in tasks:
            (duplicates if task_id in seen else seen).add(task_id)
        if duplicates:
            raise ValueError(f"tasks lists duplicate task ids: {sorted(duplicates)}")
        return list(tasks)
    raise ValueError(
        "tasks must be None, a task-file path or a list of task ids, "
        f"got {type(tasks).__name__}")


def _validate_split(split: Any) -> None:
    """An explicit split (``train`` and ``test``, optionally ``val`` and
    ``reserved``; pairwise disjoint lists of task ids) or a ratio split.
    Whether the lists cover the loaded task set is stage 0's check (D2):
    the tasks are not loaded yet."""
    if not isinstance(split, dict):
        raise ConfigError(
            f"split must be a mapping, got {type(split).__name__}")
    keys = frozenset(split)
    if "ratio" in keys:
        ratio = split["ratio"]
        if not isinstance(ratio, (int, float)) or not 0.0 < ratio < 1.0:
            raise ValueError(f"split ratio must be in (0, 1), got {ratio!r}")
        seed = split.get("seed", 0)
        if not isinstance(seed, int) or isinstance(seed, bool):
            raise ValueError(f"split seed must be an int, got {seed!r}")
        if keys - frozenset(("ratio", "seed")):
            raise ValueError(
                f"split mixes ratio and explicit lists: {sorted(keys)}")
        return
    if not SPLIT_REQUIRED_KEYS <= keys or keys - set(SPLIT_LIST_KEYS):
        raise ConfigError(
            "split must give the lists 'train' and 'test' (optionally "
            "'val' and 'reserved'), or {'ratio': float, 'seed': int}, got "
            f"keys {sorted(keys, key=str)}")
    lists = split_lists(split)
    for name, value in lists.items():
        if (not isinstance(value, list)
                or not all(isinstance(t, str) for t in value)):
            raise ValueError(
                f"split[{name!r}] must be a list of task-id strings, "
                f"got {value!r}")
    for index, first in enumerate(SPLIT_LIST_KEYS):
        for second in SPLIT_LIST_KEYS[index + 1:]:
            overlap = sorted(set(lists[first]) & set(lists[second]))
            if overlap:
                raise ConfigError(
                    f"split lists {first!r} and {second!r} overlap on: "
                    f"{overlap}")


def split_lists(split: Dict[str, Any]) -> Dict[str, Any]:
    """The four lists of an explicit split in ``SPLIT_LIST_KEYS`` order;
    an absent or null optional list is empty. Values are not checked."""
    lists = {}
    for name in SPLIT_LIST_KEYS:
        value = split.get(name)
        if value is None and name not in SPLIT_REQUIRED_KEYS:
            value = []
        lists[name] = value
    return lists


def _check_val_tasks_exist(split: Optional[Dict[str, Any]],
                           phases: Dict[str, PhaseSpec]) -> None:
    """A practice phase on ``val`` needs an explicit, non-empty val list
    (a ratio split derives train and test only)."""
    on_val = sorted(name for name, spec in phases.items()
                    if isinstance(spec, ExecutePhaseSpec)
                    and spec.tasks == "val")
    if not on_val:
        return
    if not isinstance(split, dict) or "ratio" in split \
            or not split_lists(split)["val"]:
        raise ConfigError(
            f"phase(s) {on_val} run tasks 'val' but the split has no "
            "non-empty explicit 'val' list")


def _is_positive_int(value: Any) -> bool:
    """True for a positive int; bool is an int subclass but never a budget."""
    return (isinstance(value, int) and not isinstance(value, bool)
            and value > 0)


def _validate_input_cap(value: Any, where: str) -> None:
    """Check a ``max_input_tokens`` value: positive int, or null.

    Null defers input enforcement until a full run's calibration data
    exists (converged v1 decision): the threshold only flags, never aborts.
    The flagging side lives in the call pipeline; here only the type is
    checked.
    """
    if value is None or _is_positive_int(value):
        return
    raise ConfigError(
        f"{where} must be a positive int or null (null = measure only), "
        f"got {value!r}")


def _validate_token_budgets(budgets: Any) -> Dict[str, Any]:
    """Validate ``token_budgets``; returns a deep copy so the frozen config
    is never aliased to the caller's mapping (same contract as
    model_options)."""
    if not isinstance(budgets, dict):
        raise ConfigError(
            f"token_budgets must be a mapping, got {type(budgets).__name__}")
    unknown = set(budgets) - set(_TOKEN_BUDGET_KEYS)
    if unknown:
        raise ConfigError(
            f"token_budgets has unknown keys {sorted(unknown, key=str)}, "
            f"expected a subset of {list(_TOKEN_BUDGET_KEYS)}")
    if not budgets:
        # Absent/empty: no budgets configured (the helper then fails closed).
        return {}
    default = budgets.get("default_max_output_tokens")
    if not _is_positive_int(default):
        raise ConfigError(
            "token_budgets is present but default_max_output_tokens is "
            "missing or not a positive int; it is required whenever "
            "token_budgets is given and is the fallback cap for every role "
            f"without its own entry, got {default!r}")
    if "max_input_tokens" in budgets:
        _validate_input_cap(budgets["max_input_tokens"],
                            "token_budgets.max_input_tokens")
    roles = budgets.get("roles", {})
    if not isinstance(roles, dict):
        raise ConfigError(
            "token_budgets.roles must be a mapping of role -> budget entry, "
            f"got {type(roles).__name__}")
    unknown_roles = set(roles) - set(ROLE_DEFAULTS)
    if unknown_roles:
        raise ConfigError(
            f"token_budgets.roles has unknown roles "
            f"{sorted(unknown_roles, key=str)}, expected a subset of "
            f"{list(ROLE_DEFAULTS)}")
    for role, entry in roles.items():
        if not isinstance(entry, dict):
            raise ConfigError(
                f"token_budgets.roles[{role!r}] must be a mapping with "
                f"max_output_tokens (and optionally max_input_tokens), "
                f"got {entry!r}")
        unknown_keys = set(entry) - set(_ROLE_BUDGET_KEYS)
        if unknown_keys:
            raise ConfigError(
                f"token_budgets.roles[{role!r}] has unknown keys "
                f"{sorted(unknown_keys, key=str)}, expected a subset of "
                f"{list(_ROLE_BUDGET_KEYS)}")
        if not _is_positive_int(entry.get("max_output_tokens")):
            raise ConfigError(
                f"token_budgets.roles[{role!r}].max_output_tokens is "
                "required and must be a positive int; omit the role entry "
                "to fall back to default_max_output_tokens")
        if "max_input_tokens" in entry:
            _validate_input_cap(
                entry["max_input_tokens"],
                f"token_budgets.roles[{role!r}].max_input_tokens")
    frozen = dict(budgets)
    if "roles" in frozen:
        frozen["roles"] = {role: dict(entry)
                           for role, entry in frozen["roles"].items()}
    return frozen


@dataclass
class ExperimentConfig:
    """All method parameters of one experiment (frozen into the manifest)."""

    benchmark: str
    models: Dict[str, str]
    n_attempts_strong: int = 1
    n_attempts_weak: int = 1
    #: The task division: explicit train / val / test / reserved lists
    #: (val and reserved optional) or ratio+seed.
    split: Optional[Dict[str, Any]] = None
    #: The experiment's task set: None (plugin's full set), a list of raw
    #: task ids, or a task-file path (plugin-interpreted). Stage 0 loads
    #: exactly this; explicit split lists must then cover it exactly.
    tasks: Union[None, str, List[str]] = None
    #: The method, as a sequence of phase LOCAL names (R9). Position i
    #: (0-based) is the phase the ledger and the per-phase directories
    #: label ``p{i+1:02d}:<name>``; a name may repeat (the reference
    #: method's three learn phases share one definition).
    sequence: List[str] = field(default_factory=list)
    #: The parsed phase definitions, keyed by local name: raw mappings on
    #: the way in (YAML / a frozen manifest), ExecutePhaseSpec /
    #: LearnPhaseSpec afterwards (parse_phases runs the load-time
    #: checklist in __post_init__).
    phases: Dict[str, PhaseSpec] = field(default_factory=dict)
    #: How many times the phase driver may re-dispatch one unit the
    #: verdict ruled invalid (R9); after the limit the unit stays a hole
    #: with cause ``invalid_redispatch_exhausted``. A method parameter:
    #: accepting holes changes what is measured, so it freezes.
    invalid_redispatch_limit: int = DEFAULT_INVALID_REDISPATCH_LIMIT
    #: Named-rule selections; missing keys are filled from DEFAULT_RULES,
    #: and stage 0 validates every name against the rule registries.
    rules: Dict[str, str] = field(default_factory=dict)
    #: Prompt name -> digest; filled by the prompt registry (B2) when the
    #: stages freeze the manifest, empty in the source config.
    prompts_digests: Dict[str, str] = field(default_factory=dict)
    #: Model NAME -> extra chat-call parameters (e.g. ``reasoning_effort``)
    #: forwarded to the endpoint for every call of that model, whichever
    #: role makes it. Changes what the model produces, so it is part of
    #: the experiment's frozen identity, not an operational setting.
    model_options: Dict[str, Dict[str, Any]] = field(default_factory=dict)
    #: Per-role token budgets (schema v2), the single source of every call's
    #: caps: ``default_max_output_tokens`` (positive int, required when this
    #: mapping is non-empty) is the fallback for roles without an entry;
    #: ``max_input_tokens`` (positive int or null = measure only) is global;
    #: ``roles`` maps role names to entries carrying a required
    #: ``max_output_tokens`` and an optional ``max_input_tokens``. Why the
    #: defaults are what they are: reasoning-max models burned 5120 entirely
    #: on thinking (2026-10-11, recorded in configs/experiments/
    #: tb21_full_v2.yaml), while 65536 is the endpoint-verified safe ceiling
    #: for that family -- and a cap is a ceiling, not a spend, so capping
    #: high costs nothing when the answer is short.
    token_budgets: Dict[str, Any] = field(default_factory=dict)
    schema_version: int = CONFIG_SCHEMA_VERSION

    def __post_init__(self) -> None:
        if not self.benchmark:
            raise ValueError("benchmark is required")
        if not (_is_positive_int(self.n_attempts_strong)
                and _is_positive_int(self.n_attempts_weak)):
            raise ValueError(
                "n_attempts_strong and n_attempts_weak must be positive "
                f"ints, got {self.n_attempts_strong!r} and "
                f"{self.n_attempts_weak!r}")
        if self.split is not None:
            _validate_split(self.split)
        self.tasks = _normalise_tasks(self.tasks)
        # The phase sequence: parsed here (the load-time checklist runs
        # before anything freezes), whether the caller handed raw
        # mappings (YAML / a frozen manifest) or already-parsed specs
        # (dataclasses.replace on a loaded config). The types are checked
        # before anything is converted, so a string sequence is refused
        # instead of split into letters.
        if not isinstance(self.sequence, (list, tuple)) or not self.sequence:
            raise ConfigError(
                "sequence must be a non-empty list of phase names, got "
                f"{self.sequence!r}")
        if not isinstance(self.phases, dict) or not self.phases:
            raise ConfigError(
                "phases must be a non-empty mapping of phase name -> "
                f"definition, got {self.phases!r}")
        self.sequence = list(self.sequence)
        raw_phases = {
            name: (phase_spec_to_raw(spec)
                   if isinstance(spec, (ExecutePhaseSpec, LearnPhaseSpec))
                   else spec)
            for name, spec in self.phases.items()}
        self.phases = parse_phases(raw_phases, self.sequence)
        _check_val_tasks_exist(self.split, self.phases)
        if not _is_positive_int(self.invalid_redispatch_limit):
            raise ConfigError(
                "invalid_redispatch_limit must be a positive int, got "
                f"{self.invalid_redispatch_limit!r}")
        unknown_rules = set(self.rules) - set(RULE_KEYS)
        if unknown_rules:
            raise ValueError(
                f"unknown rule keys {sorted(unknown_rules)}, "
                f"expected subset of {list(RULE_KEYS)}")
        for key, name in self.rules.items():
            if not isinstance(name, str) or not name:
                raise ValueError(
                    f"rules[{key!r}] must be a non-empty rule name, "
                    f"got {name!r}")
        # Complete the rule table (a fresh dict: never alias DEFAULT_RULES
        # or the caller's mapping), keys in RULE_KEYS order.
        self.rules = {key: self.rules.get(key, DEFAULT_RULES[key])
                      for key in RULE_KEYS}
        self.models = dict(self.models)
        unknown = set(self.models) - set(ROLE_DEFAULTS)
        if unknown:
            raise ValueError(
                f"unknown model roles {sorted(unknown)}, "
                f"expected subset of {list(ROLE_DEFAULTS)}")
        strong = self.models.get("executor_strong")
        weak = self.models.get("executor_weak")
        if not strong or not weak:
            raise ValueError(
                "models must define 'executor_strong' and 'executor_weak'")
        # Fill the role table from the data defaults.
        for role, anchor in ROLE_DEFAULTS.items():
            self.models.setdefault(role, weak if anchor == "weak" else strong)
        # Extra per-model chat-call parameters: keyed by model NAME, so they
        # are validated against the completed role table (any model a role
        # names is acceptable, not just the two anchors). Checked AFTER the
        # table is filled, and copies replace the caller's mapping so a later
        # mutation there cannot change the frozen value.
        known_models = set(self.models.values())
        unknown_models = set(self.model_options) - known_models
        if unknown_models:
            raise ValueError(
                f"model_options names unknown model(s) "
                f"{sorted(unknown_models)}; models in the role table: "
                f"{sorted(known_models)}")
        for name, options in self.model_options.items():
            if not isinstance(options, dict) or not options:
                raise ValueError(
                    f"model_options[{name!r}] must be a non-empty dict of "
                    f"chat-call parameters, got {options!r}")
            reserved = sorted(set(options) & set(MODEL_OPTIONS_RESERVED_KEYS),
                               key=str)
            if reserved:
                guidance = []
                if "max_tokens" in reserved:
                    guidance.append(
                        "max_tokens lives in token_budgets (schema v2): give "
                        "token_budgets.default_max_output_tokens, and "
                        "token_budgets.roles.<role>.max_output_tokens for "
                        "per-role caps")
                others = [key for key in reserved if key != "max_tokens"]
                if others:
                    guidance.append(
                        "not provider knobs (the client owns the request "
                        "shape): " + ", ".join(others) + "; model_options "
                        "only forwards sampling knobs such as "
                        "reasoning_effort")
                raise ConfigError(
                    f"model_options[{name!r}] carries reserved key(s) "
                    f"{reserved}: " + "; ".join(guidance))
            try:
                json.dumps(options)
            except (TypeError, ValueError) as exc:
                raise ValueError(
                    f"model_options[{name!r}] must be JSON-serialisable "
                    f"(it freezes into the manifest): {exc}") from None
        self.model_options = {name: dict(options) for name, options
                              in self.model_options.items()}
        # Token budgets: validated and deep-copied here, so the frozen config
        # cannot change through the caller's mapping and stage 0's replace()
        # re-validation is a no-op on an already-valid structure.
        self.token_budgets = _validate_token_budgets(self.token_budgets)

    def max_output_tokens_for(self, role: str) -> int:
        """Effective output cap for a role.

        ``roles[role].max_output_tokens`` when the role has an entry, else
        ``default_max_output_tokens``. Fails closed when no budgets are
        configured: returning any number here would resurrect the dead 5120
        default this schema removed, so the pipeline treats it as a hard
        config error (every experiment config carries token_budgets).
        """
        if not self.token_budgets:
            raise ConfigError(
                "token_budgets not configured: add "
                "token_budgets.default_max_output_tokens to the experiment "
                "config")
        if role not in ROLE_DEFAULTS:
            raise KeyError(
                f"unknown model role {role!r}; known: {list(ROLE_DEFAULTS)}")
        entry = self.token_budgets.get("roles", {}).get(role)
        if entry is not None:
            return entry["max_output_tokens"]
        return self.token_budgets["default_max_output_tokens"]

    def max_input_tokens_for(self, role: str) -> Optional[int]:
        """Effective input/context cap for a role, or None when unset.

        ``roles[role].max_input_tokens`` wins, then the global
        ``token_budgets.max_input_tokens``; both are optional and ``None``
        means "measure only" locally.  The TB plugin forwards a non-None
        value to the remote Terminus agent as ``model_info.max_input_tokens``.
        """
        if role not in ROLE_DEFAULTS:
            raise KeyError(
                f"unknown model role {role!r}; known: {list(ROLE_DEFAULTS)}")
        if not self.token_budgets:
            return None
        entry = self.token_budgets.get("roles", {}).get(role)
        if entry is not None and "max_input_tokens" in entry:
            return entry["max_input_tokens"]
        return self.token_budgets.get("max_input_tokens")

    def to_dict(self) -> Dict[str, Any]:
        """The freezable payload: every field, values included as they are,
        with the parsed phase specs back in their raw (JSON-safe) form so
        ``from_dict(to_dict(x))`` round-trips -- B4's resume comparison
        depends on that equality."""
        payload = {f.name: getattr(self, f.name) for f in fields(self)}
        payload["phases"] = {name: phase_spec_to_raw(spec)
                             for name, spec in self.phases.items()}
        return payload

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "ExperimentConfig":
        if not isinstance(data, dict):
            raise TypeError(
                f"config must be a mapping, got {type(data).__name__}")
        known = {f.name for f in fields(cls)}
        # Schema version first, so a record from newer code says "needs
        # newer code" and one from older code says "convert it" instead of
        # drowning in unknown-key errors its own schema would explain. The
        # config IS the experiment's identity: an unknown key is a typo or
        # a version mismatch, and dropping it silently once ran a new config
        # on old code with dead defaults.
        _check_schema_version(
            data.get("schema_version", CONFIG_SCHEMA_VERSION), "config")
        unknown = [key for key in data if key not in known]
        if unknown:
            raise ConfigError(
                f"unknown config keys {sorted(unknown, key=str)}; known keys: "
                f"{sorted(known)}")
        return cls(**{k: v for k, v in data.items() if k in known})


def _check_schema_version(version: Any, where: str) -> None:
    """Refuse every schema version other than this code's."""
    if version != CONFIG_SCHEMA_VERSION or isinstance(version, bool):
        raise ConfigError(
            f"{where} has schema_version {version!r}; this code reads "
            f"schema {CONFIG_SCHEMA_VERSION} only (regenerate the config "
            "with scripts/run/build_paper_configs.py)")


def _absolute_path(value: str, config_dir: Path) -> str:
    """A path from the config file as the absolute string the manifest
    freezes: ``~`` expanded, a relative path taken relative to the config
    file's directory (never the cwd a run or resume started from)."""
    path = Path(value).expanduser()
    if not path.is_absolute():
        path = config_dir / path
    return str(path.resolve())


def load_config(path: str) -> ExperimentConfig:
    """Load one experiment config from a YAML file.

    Relative paths inside the config are relative to the directory of the
    real config file: ``path`` is resolved first, so a symlink to a config
    behaves exactly like the config itself.

    A ``tasks`` string is a task-file path; a relative one is resolved
    against the config file's directory and stored absolute (``~`` is
    expanded), so the frozen value does not depend on the cwd a run or a
    resume was started from. A ``tasks`` list is kept as is.

    A schema version other than this code's and unknown top-level keys
    are ConfigErrors naming the offender.
    """
    import yaml  # function-local: see the module docstring

    config_path = Path(path)
    # Relative paths inside the config are relative to the REAL config
    # file: loading it through a symlink must not change what they name.
    config_dir = config_path.resolve().parent
    with open(config_path, "r", encoding="utf-8") as fh:
        data = yaml.safe_load(fh)
    if not isinstance(data, dict):
        raise ValueError(f"{path} does not contain a YAML mapping")
    _check_schema_version(data.get("schema_version"), str(path))
    known_file_keys = {f.name for f in fields(ExperimentConfig)}
    unknown = [key for key in data if key not in known_file_keys]
    if unknown:
        raise ConfigError(
            f"{path} has unknown top-level key(s) {sorted(unknown, key=str)}; "
            f"known keys: {sorted(known_file_keys)}")
    tasks = data.get("tasks")
    if isinstance(tasks, str) and tasks.strip():
        data["tasks"] = _absolute_path(tasks, config_dir)
    # The external-campaign score file follows the tasks-path rule: a
    # relative path names a file relative to the config file, and the
    # frozen value is absolute, so the control's identity never depends
    # on the cwd a run or a resume started from.
    for name, spec in (data.get("phases") or {}).items():
        if not isinstance(spec, dict):
            continue
        compare = spec.get("compare")
        if not isinstance(compare, dict):
            continue
        external = compare.get("external")
        if not isinstance(external, dict) or "path" not in external:
            continue
        external["path"] = _absolute_path(external["path"], config_dir)
    return ExperimentConfig.from_dict(data)
